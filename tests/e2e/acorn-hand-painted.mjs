import assert from 'node:assert/strict';
import { chromium } from 'playwright';
const browser = await chromium.launch();
const base = process.env.E2E_BASE_URL || 'http://localhost:3000';
const errors = [];
try {
  const page = await browser.newPage({ viewport: { width: 390, height: 844 } });
  page.on('pageerror', (error) => errors.push(error.message));
  await page.route('**/art/acorn-hand/title.png*', (route) => route.abort());
  await page.goto(`${base}/acorn-hand`);
  await page.getByRole('button', { name: 'Retry artwork' }).waitFor();
  const fallback = await page.locator('.ah-title-art').evaluate((c) => c.toDataURL());
  // A missing painting must never gate the new-run control.
  assert.equal(await page.getByTestId('new-run').isEnabled(), true);
  await page.unroute('**/art/acorn-hand/title.png*');
  await page.getByRole('button', { name: 'Retry artwork' }).click();
  await page.waitForFunction(() => window.__acorn().art.loaded.includes('title'));
  await page.waitForFunction((before) => document.querySelector('.ah-title-art').toDataURL() !== before, fallback);
  await page.locator('main[data-painted-table="true"]').waitFor();
  assert.equal(await page.getByRole('button', { name: 'Retry artwork' }).count(), 0);
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1));
  await page.getByTestId('new-run').click();
  await page.getByTestId('start').click();
  await page.waitForFunction(() => window.__acorn().art.loaded.includes('suits'));
  assert.equal(await page.locator('[data-testid^="card-"]').count(), 8);
  await page.getByTestId('card-0').click();
  assert.equal(await page.getByTestId('play').isEnabled(), true);
  // Nuts and the chips and mult plaques: the emoji and plain boxes until their paintings load, then the paintings.
  const tokens = await browser.newPage({ viewport: { width: 1280, height: 860 } });
  tokens.on('pageerror', (error) => errors.push(error.message));
  const tokenArt = /\/art\/acorn-hand\/(nuts|counters)\.png/;
  await tokens.route(tokenArt, (route) => route.abort());
  await tokens.goto(`${base}/acorn-hand`); await tokens.locator('main[data-ready="true"]').waitFor();
  await tokens.getByTestId('new-run').click(); await tokens.getByTestId('start').click(); await tokens.getByTestId('hand').waitFor();
  await tokens.waitForFunction(() => ['nuts', 'counters'].every((k) => window.__acorn().art.failed.includes(k)));
  assert.match(await tokens.getByTestId('nuts').innerText(), /🌰/);
  assert.equal(await tokens.locator('.ah-nut').count(), 0);
  assert.equal(await tokens.locator('.ah-plaque').count(), 0);
  await tokens.unroute(tokenArt);
  await tokens.getByRole('button', { name: 'Retry artwork' }).click();
  await tokens.locator('[data-testid="nuts"] .ah-nut').waitFor();
  assert.equal(await tokens.locator('[data-testid="nut-pile"] .ah-nut').count(), 10);
  assert.doesNotMatch(await tokens.getByTestId('nuts').innerText(), /🌰/);
  assert.equal(await tokens.locator('[data-testid="chips"].ah-plaque, [data-testid="mult"].ah-plaque').count(), 2);
  // Table companions must repaint from their code fallback to the painted friends after a retry.
  const pals = await browser.newPage({ viewport: { width: 1280, height: 860 } });
  pals.on('pageerror', (error) => errors.push(error.message));
  await pals.route('**/art/acorn-hand/charms-0.png*', (route) => route.abort());
  await pals.goto(`${base}/acorn-hand`); await pals.locator('main[data-ready="true"]').waitFor();
  await pals.getByTestId('new-run').click(); await pals.getByTestId('start').click();
  await pals.waitForFunction(() => window.__acorn().art.failed.includes('charms-0'));
  const oldPals = await pals.getByTestId('pals').locator('canvas').evaluateAll((canvases) => canvases.map((c) => c.toDataURL()));
  assert.equal(oldPals.length, 2);
  await pals.unroute('**/art/acorn-hand/charms-0.png*');
  await pals.getByRole('button', { name: 'Retry artwork' }).click();
  await pals.waitForFunction(() => window.__acorn().art.loaded.includes('charms-0'));
  await pals.waitForFunction((before) => [...document.querySelectorAll('[data-testid="pals"] canvas')].every((c, i) => c.toDataURL() !== before[i]), oldPals);
  assert.deepEqual(errors, []);
  console.log('PASS Acorn Hand painted art: missing-image fallback, retry, asynchronous canvas redraw, painted table, phone fit, playable painted cards, painted nuts and plaques with their fallback, and painted Dora/Enzo companions after retry.');
} finally { await browser.close(); }
