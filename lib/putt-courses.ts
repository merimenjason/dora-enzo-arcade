/** Puttering Paws courses: every hole as a tile map. No DOM or Three.js.
 *
 *  One character is one tile, one world unit across; rows run north (top) to south, so +z is south and +x is east.
 *  `.` felt · `s` dust-bath sand · `w` pond · `#` hay bale or windmill wall · ` ` nothing
 *  `T` tee · `C` cup · `a` golden acorn · `m` mushroom bumper
 *  `>` `<` `^` `v` a ramp rising one step toward east, west, north or south
 *  `[` `]` `{` `}` a felt tile with its north-west, north-east, south-west or south-east half walled off on the diagonal
 *  `levels` (optional, same shape) gives each tile's height in steps of a quarter tile; a space is 0.
 *  With `drops`, a ledge between two felt tiles is a one-way drop down instead of a wall.
 *  `proof` is a line of putts that holes out in par or better, and `acornProof` one that also picks up the acorn;
 *  `tests/putt.mjs` replays both from the tee. Each putt is [angle in degrees (0 east, 90 south), power 0-1, seconds to wait first]. */
export type CourseId = 'clover' | 'lantern';
export type Dir = 'n' | 's' | 'e' | 'w';
export type Mound = { x: number; z: number; r: number; h: number };
export type MoverSpec = { kind: 'boar' | 'bale'; a: [number, number]; b: [number, number]; period: number; phase?: number; r: number };
export type TunnelSpec = { from: [number, number]; to: [number, number]; dir: Dir };
export type WindmillSpec = { at: [number, number]; axis: 'ns' | 'ew'; period: number; phase?: number };
export type Shot = [angle: number, power: number, wait?: number];
export type HoleSpec = {
  id: string; name: string; par: number; tip: string; map: string[]; levels?: string[]; drops?: boolean;
  mounds?: Mound[]; movers?: MoverSpec[]; tunnels?: TunnelSpec[]; windmills?: WindmillSpec[];
  proof: Shot[]; acornProof: Shot[];
};

