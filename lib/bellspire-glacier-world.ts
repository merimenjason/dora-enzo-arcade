export type FallState = 'plug' | 'water' | 'frozen';
type Tile = readonly [number, number];
export type GlacierFall = { c: number; w: number; top: number; bottom: number; timed?: boolean; starts?: FallState };
export type SunSocket = { at: Tile; path: Tile[]; sun?: true; from?: number; fall?: number };
export type GlacierRoom = { falls?: GlacierFall[]; sockets?: SunSocket[]; icicles?: Tile[]; perch?: Tile };
type IceRoom = Room & { glacier: GlacierRoom };
const rows = (drawing: string) => drawing.trim().split('\n').map(row => row.replaceAll(' ', ''));
export const glacierFlag = (room: string, kind: 'sun' | 'water' | 'frozen', index: number) => `glacier:${room}:${kind}:${index}`;
export const isGlacierRoom = (room: Room) => !!room.glacier;

/** Shared by collision, drawing, and the planner; a fall never occupies an extra tile off its painted edges. */
export function glacierTile(room: Room, c: number, r: number, cols: number, rowsPerCell: number, state: (i: number) => FallState) {
  const x = c - room.gx * cols, y = r - room.gy * rowsPerCell;
  const mark = room.rows[y]?.[x];
  const fall = room.glacier?.falls?.findIndex(f => x >= f.c && x < f.c + f.w && y >= f.top && y < f.bottom) ?? -1;
  const mode = fall >= 0 ? state(fall) : null;
  return { fall, solid: mark === SLICK || mode === 'plug', slick: mark === SLICK, climb: mark === ICE_WALL || mode === 'frozen' };
}

