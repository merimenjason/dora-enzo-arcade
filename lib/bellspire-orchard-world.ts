type Span = readonly [fromColumn: number, toColumn: number, row: number];
export type Graft = {
  bud: readonly [column: number, row: number];
  tie?: readonly [column: number, row: number];
  bloom: Span;
  shear?: Span;
};

export const graftFlag = (room: string, index: number, stage: 'bloom' | 'shear') =>
  `orchard:${room}:${index}:${stage}`;

/** The top of the painted branch is also its exact collision edge. */
export function graftSpans(room: Room, hasFlag: (flag: string) => boolean, tile: number, cols: number, rows: number) {
  const ox = room.gx * cols * tile, oy = room.gy * rows * tile;
  return (room.grafts ?? []).flatMap((graft, index) =>
    (['bloom', 'shear'] as const).flatMap((stage) => {
      const span = graft[stage], key = graftFlag(room.id, index, stage);
      if (!span || !hasFlag(key)) return [];
      return [{ x0: ox + span[0] * tile, x1: ox + span[1] * tile, y: oy + span[2] * tile, key }];
    }));
}

