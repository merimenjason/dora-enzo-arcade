// Kit Parade's thirty levels, as data. Each map row is one line of 8-pixel tiles; a number before a character repeats it.
//   ' ' air   # soft earth   = pebble stone (nothing digs it)   - half-height stone   _ half-height earth
//   / \ earth slopes   < > one-way hay (dig through it only the way the arrows point)   { } hay belts (carry kits left or right)
//   b hay bales   ~ water   E the burrow the kits pop out of   X the home burrow
// Objects are in tiles: lily pads drift on the water, seesaws tip toward the heavier side, fans blow kits upward.
// Every level carries a solution (jobs on set ticks, by kit number) that the tests replay for three stars, and the
// indices of its key jobs: take any one away and the level can't be cleared.
import type { Action, Job } from './parade-game.js';

export type LevelDef = {
  id: string; name: string; world: number; hint: string;
  map: string[];
  /** Kits in the parade, how many must get home, ticks between kits, and the time limit in seconds. */
  kits: number; need: number; rate: number; time: number;
  /** The way the kits face when they pop out (right unless set). */
  dir?: 1 | -1;
  jobs: Partial<Record<Job, number>>;
  pads?: { x: number; y: number; w: number; min: number; max: number; every?: number }[];
  seesaws?: { x: number; y: number; half: number; amp?: number; tilt?: 1 | -1 }[];
  fans?: { x: number; y: number; w: number; h: number }[];
  /** Three stars: no more than `jobs` jobs, and everyone who gets home is home by `time` seconds. */
  par: { jobs: number; time: number };
  solution: Action[];
  key: number[];
};

