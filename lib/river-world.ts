export type Point = { x: number; y: number };
export type Marker = Point & { type: string; col: number; row: number };
export type Reach = {
  id: string; title: string; district: number; arrival: string; rows: string[];
  width: number; height: number; markers: Marker[]; guardian: boolean;
};

const pieces = new Set('DEgjqJmoOXsSHuwkTV0123456789AB');
function reach(id: string, title: string, district: number, arrival: string, ascii: string, guardian = false): Reach {
  const rows = ascii.trim().split('\n').map(row => row.trim());
  const width = Math.max(...rows.map(row => row.length));
  const markers: Marker[] = [];
  rows.forEach((line, row) => [...line].forEach((type, col) => {
    if (pieces.has(type)) markers.push({ type, row, col, x: col * TILE + TILE / 2, y: row * TILE + TILE / 2 });
  }));
  return { id, title, district, arrival, rows, width, height: rows.length, markers, guardian };
}

