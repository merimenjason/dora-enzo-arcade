// Misprint: the thirty pages, in three zines of ten. Each page is drawn as text, one character a cell, at the plates'
// starting registration (both offsets 0, 0):
//   .  bare paper            P  pink ink (Dora's)      T  teal ink (Enzo's)      X  both inks: purple, solid for both
//   Y  yellow key plate      p  pink ladder            t  teal ladder            k  pink and teal ladder (purple)
//   1  pink stamp            2  teal stamp             3  hidden pink, printed while a teal stamp is pressed
//   4  hidden teal, printed while a pink stamp is pressed
//   m n +  registration marks (pink, teal, both): ink that must stay on the paper like any other, so they set how far a
//          plate can slide, but they hold nobody
//   ^ > v <  one-way folds (a chinchilla can't move into one against its arrow)
//   D E  Dora and Enzo       d e  Dora or Enzo starting on a staple tile      S  staple tile      *  the ink drop
// `par` is the move count for the second star (switching chinchilla is free). `teaches` names the idea a page
// introduces; tests/misprint.mjs checks the page can't be finished, or takes clearly longer, without it.
