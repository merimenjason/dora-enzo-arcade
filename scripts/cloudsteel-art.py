#!/usr/bin/env python3
"""Cloudsteel: brings Codex's paintings into the game.

    python3 scripts/cloudsteel-art.py frames <folder with dora-heavy.png, dora-gaze.png, enzo-offer.png>
    python3 scripts/cloudsteel-art.py frames <folder with enzo-a.png, enzo-b.png, swap.png, arch-a.png .. arch-c.png> sheets
    python3 scripts/cloudsteel-art.py decor <folder with decor-a.png .. decor-d.png>
    python3 scripts/cloudsteel-art.py textures <folder with the tex-*.png, door.png> <folder with the arch paintings>

Figures and cut-outs were painted on flat magenta. The key clears the magenta and unmixes it from the soft edges, so no
pink fringe is left round the fur. `frames` adds new paintings to a character's atlas in public/art/cloudsteel/sprites/:
the existing cells are kept exactly, each new frame is scaled to match a frame of the same character already in the
atlas and stood with its feet on the atlas's baseline, and lib/cloudsteel-sprites.ts is rewritten with the new grid.
With `sheets`, the paintings are 2x2 sheets of four figures each (see SHEETS): every figure on a sheet was painted at
one scale, so one figure on each sheet is matched to an existing frame and the other three keep their size against
it; a character with no atlas yet (the vizcacha archer) gets a new one, and an atlas whose new frames reach wider than
its cells gains room at the sides. `decor` cuts the four 2x2 set-dressing sheets into one atlas (public/art/cloudsteel/decor.webp) and writes each item's
place in it to lib/cloudsteel-decor.ts. `textures` turns the tileable textures and the big architectural pieces into
WebP.
"""
import json
import re
import sys
from pathlib import Path

import numpy as np
from PIL import Image, ImageEnhance

ROOT = Path(__file__).resolve().parent.parent
ART = ROOT / 'public' / 'art' / 'cloudsteel'
SPRITES_TS = ROOT / 'lib' / 'cloudsteel-sprites.ts'
MAGENTA = np.array([255.0, 0.0, 255.0])


def key(im):
    """flat magenta becomes clear; pixels on the edge of the background get the magenta unmixed out of them"""
    a = np.asarray(im.convert('RGB')).astype(np.float64)
    r, g, b = a[..., 0], a[..., 1], a[..., 2]
    m = (np.minimum(r, b) - g) / 255.0
    bg = (m > 0.62) & (r > 150) & (b > 150)
    # only pixels touching the background are edges: pink ears and indigo cloth inside a figure are left alone
    near = bg.copy()
    for _ in range(3):
        n = near.copy()
        n[1:] |= near[:-1]; n[:-1] |= near[1:]; n[:, 1:] |= near[:, :-1]; n[:, :-1] |= near[:, 1:]
        near = n
    edge = near & ~bg & (m > 0.12)
    alpha = np.ones(r.shape)
    alpha[bg] = 0
    alpha[edge] = np.clip(1 - (m[edge] - 0.12) / 0.5, 0.05, 1)
    out = a.copy()
    k = alpha[edge][:, None]
    out[edge] = np.clip((a[edge] - (1 - k) * MAGENTA) / k, 0, 255)
    rgba = np.dstack([out, alpha * 255]).astype(np.uint8)
    rgba[bg] = 0
    return Image.fromarray(rgba)


def bbox(im, thr=40):
    al = np.asarray(im)[..., 3] > thr
    ys, xs = np.nonzero(al)
    return xs.min(), ys.min(), xs.max() + 1, ys.max() + 1


def resize(im, w, h):
    """scales with premultiplied alpha, so clear pixels do not bleed their colour into the edge"""
    return im.convert('RGBa').resize((max(1, round(w)), max(1, round(h))), Image.LANCZOS).convert('RGBA')


def read_sheets():
    src = SPRITES_TS.read_text()
    ppm = float(re.search(r'SPRITE_PPM = ([\d.]+)', src).group(1))
    sheets = {}
    for m in re.finditer(r'  (\w+): \{ cols: (\d+), rows: (\d+), cw: (\d+), ch: (\d+), ax: ([\d.]+), ay: ([\d.]+), frames: (\[.*?\]) \}', src):
        g = m.groups()
        sheets[g[0]] = dict(cols=int(g[1]), rows=int(g[2]), cw=int(g[3]), ch=int(g[4]), ax=float(g[5]), ay=float(g[6]), frames=json.loads(g[7]))
    return ppm, sheets


def write_sheets(ppm, sheets):
    lines = [
        '// Generated by the Cloudsteel art pipeline (scripts/cloudsteel-art.py): one atlas per character in',
        '// public/art/cloudsteel/sprites/, a grid of equal cells; (ax, ay) is the figure\'s anchor in a cell (under the head, on',
        '// the ground), in pixels. Do not edit by hand.',
        f'export const SPRITE_PPM = {ppm};',
        'export type SpriteSheet = { cols: number; rows: number; cw: number; ch: number; ax: number; ay: number; frames: string[] };',
        'export const SPRITES: Record<string, SpriteSheet> = {',
    ]
    for who, s in sheets.items():
        fr = ', '.join(json.dumps(f) for f in s['frames'])
        lines.append(f"  {who}: {{ cols: {s['cols']}, rows: {s['rows']}, cw: {s['cw']}, ch: {s['ch']}, ax: {s['ax']}, ay: {s['ay']}, frames: [{fr}] }},")
    lines.append('};')
    SPRITES_TS.write_text('\n'.join(lines) + '\n')


def cells(who, s):
    atlas = Image.open(ART / 'sprites' / f'{who}.webp').convert('RGBA')
    out = {}
    for i, f in enumerate(s['frames']):
        x, y = (i % s['cols']) * s['cw'], (i // s['cols']) * s['ch']
        out[f] = atlas.crop((x, y, x + s['cw'], y + s['ch']))
    return out


def body_top(im, frac=0.16):
    """the top of the ears: the first row as wide as a head, so a staff held overhead is not counted"""
    al = np.asarray(im)[..., 3] > 40
    w = al.sum(1)
    x0, y0, x1, y1 = bbox(im)
    need = max(6, (x1 - x0) * frac)
    rows = np.nonzero(w >= need)[0]
    return rows.min()


# the new paintings: (character, frame name, file, the existing frame whose height (ears to feet) it matches, the
# height ratio to that frame, where its head sits across the cell as a fraction of the cell width or None for the
# anchor, and how wide a row must be, as a fraction of the figure's width, to count as the top of the ears: a lantern
# held overhead is wider than a staff)
FRAMES = [
    ('dora', 'heavy', 'dora-heavy.png', 'idle-back', 0.92, 0.47, 0.16),
    ('dora', 'gaze', 'dora-gaze.png', 'idle-back', 1.0, None, 0.16),
    ('enzo', 'offer', 'enzo-offer.png', 'idle-back', 1.0, None, 0.3),
]


def frames(src):
    ppm, sheets = read_sheets()
    for who in sorted({f[0] for f in FRAMES}):
        s = sheets[who]
        old = cells(who, s)
        new = {}
        for w2, name, file, ref, ratio, hx, frac in FRAMES:
            if w2 != who:
                continue
            im = key(Image.open(Path(src) / file))
            im = im.crop(bbox(im, 8))
            r = old[ref]
            ref_h = s['ay'] - body_top(r)
            k = ref_h * ratio / (im.height - body_top(im, frac))
            im = resize(im, im.width * k, im.height * k)
            # the head: the middle of the top quarter of the body
            al = np.asarray(im)[..., 3] > 40
            t = body_top(im, frac)
            band = al[t:t + max(4, int((im.height - t) * 0.25))]
            head_x = np.nonzero(band)[1].mean()
            new[name] = (im, head_x)
        # room above for anything held high
        pad = 0
        for im, _ in new.values():
            pad = max(pad, int(np.ceil(im.height - s['ay'] + 4)))
        cw, ch, ax, ay = s['cw'], s['ch'] + pad, s['ax'], s['ay'] + pad
        frames_ = s['frames'] + [n for n in new if n not in s['frames']]
        cols = s['cols']
        rows = -(-len(frames_) // cols)
        atlas = Image.new('RGBA', (cols * cw, rows * ch), (0, 0, 0, 0))
        for i, f in enumerate(frames_):
            x, y = (i % cols) * cw, (i // cols) * ch
            if f in new:
                im, head_x = new[f]
                want = ax if new_hx(f) is None else new_hx(f) * cw
                px = round(want - head_x)
                px = min(max(px, 0), cw - im.width) if im.width <= cw else (cw - im.width) // 2
                cell = Image.new('RGBA', (cw, ch), (0, 0, 0, 0))
                cell.alpha_composite(im, (px, round(ay - im.height)))
                atlas.alpha_composite(cell, (x, y))
            else:
                atlas.alpha_composite(old[f], (x, y + pad))
        atlas.save(ART / 'sprites' / f'{who}.webp', 'WEBP', quality=88, method=6)
        sheets[who] = dict(cols=cols, rows=rows, cw=cw, ch=ch, ax=ax, ay=round(ay, 1), frames=frames_)
        print(who, 'atlas', atlas.size, 'added', list(new), 'pad', pad)
    write_sheets(ppm, sheets)


def new_hx(name):
    for _, n, _, _, _, hx, _ in FRAMES:
        if n == name:
            return hx
    return None


# the tag-team duel's paintings: 2x2 sheets on magenta. (character, sheet, the four frames' names left to right, top to
# bottom (None: not this character's), the quarter that is matched to an existing frame, that frame as 'who:frame',
# and the height ratio to it). The rest of the sheet's figures for that character keep their size against it.
SHEETS = [
    ('enzo', 'enzo-b.png', ['ward', 'hop', 'f-hit', 'f-down'], 0, 'enzo:brace', 1.05),
    ('enzo', 'enzo-a.png', ['f-stance', 'sweep-wind', 'sweep', 'sweep-end'], 0, 'enzo:ward', 0.9),
    ('dora', 'swap.png', ['wait', 'tag-out', None, None], 0, 'dora:idle-side', 1.0),
    ('enzo', 'swap.png', [None, None, 'tag-out', 'ward-hit'], 2, 'enzo:idle-side', 0.92),
    ('archer', 'arch-a.png', ['idle', 'walk-0', 'walk-1', 'walk-2'], 0, 'kin:idle', 1.0),
    ('archer', 'arch-b.png', ['draw', 'aim', 'release', 'hit'], 1, 'archer:idle', 1.0),
    ('archer', 'arch-c.png', ['broken', 'down', 'bow', 'talk'], 3, 'archer:idle', 1.0),
]


# frames whose lantern was painted with a soft glow over the magenta: the pink left in the glow is turned gold
GLOWS = {'ward-hit'}


def gild(im):
    a = np.asarray(im).astype(np.float64)
    r, g, b = a[..., 0], a[..., 1], a[..., 2]
    pink = (np.minimum(r, b) - g > 30) & (r > 170)
    a[..., 1][pink] = r[pink] * 0.78
    a[..., 2][pink] = r[pink] * 0.32
    return Image.fromarray(a.astype(np.uint8))


def quarter(sheet, q):
    w, h = sheet.size
    part = sheet.crop(((q % 2) * w // 2, (q // 2) * h // 2, (q % 2 + 1) * w // 2, (q // 2 + 1) * h // 2))
    return part.crop(bbox(part, 8))


def head_x(im, frac=0.16):
    al = np.asarray(im)[..., 3] > 40
    t = body_top(im, frac)
    band = al[t:t + max(4, int((im.height - t) * 0.25))]
    return np.nonzero(band)[1].mean()


def sheets_(src):
    ppm, sheets = read_sheets()
    keyed = {}
    new = {}  # who -> {name: (im, head_x)}
    old = {who: cells(who, s) for who, s in sheets.items()}

    def height(im):
        return im.height - body_top(im)

    for who, file, names, anchor, ref, ratio in SHEETS:
        if file not in keyed:
            keyed[file] = key(Image.open(Path(src) / file))
        parts = {q: quarter(keyed[file], q) for q, n in enumerate(names) if n}
        rw, rf = ref.split(':')
        if rw in new and rf in new[rw]:
            ref_h = height(new[rw][rf][0])
        else:
            ref_h = sheets[rw]['ay'] - body_top(old[rw][rf])
        k = ref_h * ratio / height(parts[anchor])
        for q, im in parts.items():
            im = resize(gild(im) if names[q] in GLOWS else im, im.width * k, im.height * k)
            new.setdefault(who, {})[names[q]] = (im, head_x(im))
    for who, frames in new.items():
        if who in sheets:
            s = sheets[who]
            cw, ch, ax, ay, cols = s['cw'], s['ch'], s['ax'], s['ay'], s['cols']
            names = s['frames'] + [n for n in frames if n not in s['frames']]
        else:
            # a new atlas: the idle sets the anchor; cells as big as the largest frame needs
            cols = 4
            hx = frames['idle'][1]
            ax = max(hx for im, hx in frames.values()) + 4
            cw = int(np.ceil(ax + max(im.width - hx for im, hx in frames.values()) + 4))
            ay = max(im.height for im, _ in frames.values()) + 4
            ch = int(np.ceil(ay + 4))
            names = list(frames)
            old[who] = {}
        # room on top and at the sides for anything that reaches past the cells
        top = max(0, int(np.ceil(max(im.height for im, _ in frames.values()) - ay + 4)))
        left = max(0, int(np.ceil(max(hx for _, hx in frames.values()) - ax + 2)))
        right = max(0, int(np.ceil(max(im.width - hx for im, hx in frames.values()) - (cw - ax) + 2)))
        CW, CH, AX, AY = cw + left + right, ch + top, ax + left, ay + top
        rows = -(-len(names) // cols)
        atlas = Image.new('RGBA', (cols * CW, rows * CH), (0, 0, 0, 0))
        for i, f in enumerate(names):
            x, y = (i % cols) * CW, (i // cols) * CH
            if f in frames:
                im, hx = frames[f]
                atlas.alpha_composite(im, (x + round(AX - hx), y + round(AY - im.height)))
            else:
                atlas.alpha_composite(old[who][f], (x + left, y + top))
        atlas.save(ART / 'sprites' / f'{who}.webp', 'WEBP', quality=88, method=6)
        sheets[who] = dict(cols=cols, rows=rows, cw=CW, ch=CH, ax=round(AX, 1), ay=round(AY, 1), frames=names)
        print(who, 'atlas', atlas.size, 'added', list(frames), 'room', top, left, right)
    write_sheets(ppm, sheets)


# the set dressing: sheet, quarter (0 top-left, 1 top-right, 2 bottom-left, 3 bottom-right) and name
DECOR = [
    ('decor-a', 0, 'banner'), ('decor-a', 1, 'brazier'), ('decor-a', 2, 'stele'), ('decor-a', 3, 'tapestry'),
    ('decor-b', 0, 'relief-puma'), ('decor-b', 1, 'offering'), ('decor-b', 2, 'ferns'), ('decor-b', 3, 'statue'),
    ('decor-c', 0, 'jars'), ('decor-c', 1, 'relief-condor'), ('decor-c', 2, 'column'), ('decor-c', 3, 'vines'),
    ('decor-d', 0, 'relief-serpent'), ('decor-d', 1, 'cargo'), ('decor-d', 2, 'lamp'), ('decor-d', 3, 'pennants'),
]


def decor(src):
    cell = 512
    atlas = Image.new('RGBA', (cell * 4, cell * 4), (0, 0, 0, 0))
    out = {}
    sheets = {}
    for i, (sheet, q, name) in enumerate(DECOR):
        if sheet not in sheets:
            sheets[sheet] = key(Image.open(Path(src) / f'{sheet}.png'))
        s = sheets[sheet]
        w, h = s.size
        part = s.crop(((q % 2) * w // 2, (q // 2) * h // 2, (q % 2 + 1) * w // 2, (q // 2 + 1) * h // 2))
        part = part.crop(bbox(part, 8))
        k = min((cell - 8) / part.width, (cell - 8) / part.height)
        part = resize(part, part.width * k, part.height * k)
        x, y = (i % 4) * cell, (i // 4) * cell
        # bottom-centred in its cell, with a clear gutter so mipmaps do not bleed
        px, py = x + (cell - part.width) // 2, y + cell - 4 - part.height
        atlas.alpha_composite(part, (px, py))
        W = cell * 4
        out[name] = dict(u0=round(px / W, 5), v0=round(1 - (py + part.height) / W, 5), u1=round((px + part.width) / W, 5), v1=round(1 - py / W, 5), aspect=round(part.width / part.height, 4))
    atlas.save(ART / 'decor.webp', 'WEBP', quality=86, method=6)
    lines = ['// Generated by scripts/cloudsteel-art.py: where each piece of set dressing sits in public/art/cloudsteel/decor.webp',
             '// (texture coordinates, v up) and its width over its height. Do not edit by hand.',
             'export type DecorItem = { u0: number; v0: number; u1: number; v1: number; aspect: number };',
             'export const DECOR: Record<string, DecorItem> = {']
    for name, d in out.items():
        lines.append(f"  '{name}': {{ u0: {d['u0']}, v0: {d['v0']}, u1: {d['u1']}, v1: {d['v1']}, aspect: {d['aspect']} }},")
    lines.append('};')
    (ROOT / 'lib' / 'cloudsteel-decor.ts').write_text('\n'.join(lines) + '\n')
    print('decor atlas', atlas.size, len(out), 'items')


def textures(src, arch):
    src, arch = Path(src), Path(arch)
    # the masonry was painted a strong blue: it is calmed to sit with the slate of the terrace and the painted figures
    for n, sat in [('tex-ashlar', 0.5), ('tex-thatch', 1), ('tex-wood', 1), ('tex-cliff', 0.75), ('tex-paving', 1)]:
        im = Image.open(src / f'{n}.png').convert('RGB').resize((1024, 1024), Image.LANCZOS)
        im = ImageEnhance.Color(im).enhance(sat)
        im.save(ART / f'{n[4:]}.webp', 'WEBP', quality=84, method=6)
    ImageEnhance.Color(Image.open(src / 'tex-trim.png').convert('RGB').resize((1024, 256), Image.LANCZOS)).enhance(0.75).save(ART / 'trim.webp', 'WEBP', quality=86, method=6)
    Image.open(src / 'door.png').convert('RGB').resize((1024, 683), Image.LANCZOS).save(ART / 'door.webp', 'WEBP', quality=84, method=6)
    Image.open(arch / 'mural.png').convert('RGB').resize((1536, 768), Image.LANCZOS).save(ART / 'mural.webp', 'WEBP', quality=84, method=6)
    ImageEnhance.Color(Image.open(arch / 'gate-arch.png').convert('RGB').resize((512, 768), Image.LANCZOS)).enhance(0.6).save(ART / 'pillar.webp', 'WEBP', quality=84, method=6)
    for n, w in [('condor-relief', 1536), ('sun-lamp', 768)]:
        im = key(Image.open(arch / f'{n}.png'))
        im = im.crop(bbox(im, 8))
        k = w / im.width
        resize(im, im.width * k, im.height * k).save(ART / f'{n}.webp', 'WEBP', quality=88, method=6)
    print('textures done')


if __name__ == '__main__':
    what = sys.argv[1]
    if what == 'frames':
        if sys.argv[3:] == ['sheets']:
            sheets_(sys.argv[2])
        else:
            frames(sys.argv[2])
    elif what == 'decor':
        decor(sys.argv[2])
    elif what == 'textures':
        textures(sys.argv[2], sys.argv[3])
